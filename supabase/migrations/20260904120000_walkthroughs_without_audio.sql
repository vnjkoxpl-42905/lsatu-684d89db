-- The written walkthrough becomes the deliverable, and the recording optional.
--
-- `model_runs` was built on the assumption that a model run IS a recording: the
-- audio is NOT NULL and the transcript is the nullable extra. That was true of
-- the capture and it is the wrong way round for a student. She cannot skim a
-- recording, she cannot search it, she cannot sit with one line of it while she
-- works out why her own recall dropped a quantifier, and nine of the stimuli in
-- the twelve built sections were never recorded at all, so under the old shape
-- those nine could offer her nothing.
--
-- Written-first inverts it. Every stimulus in every built section now has a
-- walkthrough -- the run cut into the verbatim read, then the recall underneath
-- it, on the same boundaries the grader scores on -- and the recording is a
-- second way to take the same thing, for the stimuli that have one.
--
-- The access rule is untouched and does not need restating: the policy added in
-- 20260903210000 gates the ROW on "she has already been graded on this section",
-- so a new column on that row is behind the same gate the audio is. A
-- walkthrough is an answer key before she runs the section and a lesson after
-- it, exactly as the recording is.

alter table public.model_runs
  add column if not exists walkthrough_md text;

comment on column public.model_runs.walkthrough_md is
  'The run as a readable document: verbatim reads as blockquotes, his recall as '
  'prose beneath each. Generated by system/scripts/activity-centre/'
  'polish_transcripts.py in the vault, which may restructure and drop filler but '
  'never writes a word he did not say.';

-- Nine authored references have no recording and never will, and a NOT NULL
-- audio_path is the only thing standing between them and a student.
alter table public.model_runs
  alter column audio_path drop not null;

-- What replaces it. A row exists to give her something; one carrying neither a
-- recording nor a walkthrough is a row that can only render as an empty panel.
alter table public.model_runs
  drop constraint if exists model_runs_has_something_to_offer;
alter table public.model_runs
  add constraint model_runs_has_something_to_offer
  check (audio_path is not null or walkthrough_md is not null);
