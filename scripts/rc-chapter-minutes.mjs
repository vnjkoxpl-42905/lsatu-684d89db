/**
 * Computes the RC bootcamp's per-chapter time estimates from the real lesson
 * content and writes them to
 * src/bootcamps/rc-bootcamp/chapterMinutes.generated.ts.
 *
 * The numbers a student sees have to be true, so they are derived here rather
 * than guessed: reading words at 200 wpm, plus the literal timer minutes of any
 * timed read in the chapter, plus a minute for each screen that asks them to
 * write. Run this after any content change; a Vitest spec fails if the
 * checked-in numbers have gone stale.
 *
 *   node scripts/rc-chapter-minutes.mjs
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..');
const contentPath = join(repoRoot, 'src/bootcamps/rc-bootcamp/content.ts');
const outPath = join(repoRoot, 'src/bootcamps/rc-bootcamp/chapterMinutes.generated.ts');

export const WORDS_PER_MINUTE = 200;

/** Strip markup and count words in a repo-authored HTML string. */
function countWords(htmlString) {
  if (!htmlString) return 0;
  const text = String(htmlString)
    .replace(/<[^>]*>/g, ' ')
    .replace(/&[a-z]+;/gi, ' ')
    .trim();
  return text ? text.split(/\s+/).length : 0;
}

/** Every readable string on a screen, and the fixed minutes it demands. */
export function chapterMinutes(chapter) {
  let words = 0;
  let fixed = 0;

  for (const screen of chapter.screens) {
    words += countWords(screen.title);
    words += countWords(screen.lede);
    words += countWords(screen.body);
    words += countWords(screen.intro);
    words += countWords(screen.directive);
    words += countWords(screen.question);
    words += countWords(screen.outro);
    words += countWords(screen.task);
    if (screen.callout) words += countWords(screen.callout.body);
    if (screen.outroCallout) words += countWords(screen.outroCallout.body);
    if (screen.reveal) words += countWords(screen.reveal.html);
    for (const step of screen.steps ?? []) words += countWords(step);
    for (const beat of screen.beats ?? []) {
      words += countWords(beat.html);
      words += countWords(beat.question);
      words += countWords(beat.note);
      for (const option of beat.options ?? []) words += countWords(option);
    }
    if (screen.followUp) {
      words += countWords(screen.followUp.text);
      words += countWords(screen.followUp.html);
    }

    // A timed read costs exactly what its clock says. An untimed read is priced
    // by its passage instead, which the caller adds since passages are
    // referenced by id rather than inlined on the screen.
    if (screen.type === 'read') fixed += screen.minutes ?? 0;
    if (screen.type === 'write') fixed += 1;
  }

  return { words, fixed };
}

async function loadContent() {
  const bundle = await build({
    entryPoints: [contentPath],
    bundle: false,
    write: false,
    format: 'esm',
    target: 'es2020',
  });
  const source = bundle.outputFiles[0].text;
  const dataUrl = `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
  return import(dataUrl);
}

const { CHAPTERS, PASSAGES } = await loadContent();

const minutes = CHAPTERS.map((chapter) => {
  const { words, fixed } = chapterMinutes(chapter);

  // Passage text the student actually reads on this screen, which the screen
  // objects only reference by id.
  let passageWords = 0;
  for (const screen of chapter.screens) {
    if (screen.type === 'passage' || (screen.type === 'read' && !screen.minutes)) {
      const passage = PASSAGES[screen.passageId];
      for (const para of passage?.paras ?? []) passageWords += countWords(para);
    }
  }

  const total = (words + passageWords) / WORDS_PER_MINUTE + fixed;
  return Math.max(1, Math.round(total));
});

const file = `/**
 * GENERATED by scripts/rc-chapter-minutes.mjs — do not edit by hand.
 *
 * Per-chapter time estimates, in minutes, computed from the real lesson
 * content. Re-run the script after any content change; chapterMinutes.test.ts
 * fails if these have gone stale.
 */

export const CHAPTER_MINUTES: number[] = [${minutes.join(', ')}];

export const LESSON_MINUTES = ${minutes.reduce((a, b) => a + b, 0)};
`;

writeFileSync(outPath, file);
console.log(`wrote ${outPath}`);
console.log(`chapters: ${minutes.join(', ')}`);
console.log(`lesson total: ${minutes.reduce((a, b) => a + b, 0)} min`);
