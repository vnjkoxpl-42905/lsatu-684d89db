import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const path = process.argv[process.argv.indexOf('--pglite-module') + 1];
if (!path || !process.argv.includes('--pglite-module')) throw new Error('Provide isolated PGlite module path.');
const { PGlite } = await import(pathToFileURL(path));
const db = new PGlite();
const student = '11111111-1111-4111-8111-111111111111', admin = '22222222-2222-4222-8222-222222222222', foreign = '33333333-3333-4333-8333-333333333333';
const attempt = '44444444-4444-4444-8444-444444444444', later = '55555555-5555-4555-8555-555555555555';
let checks = 0;
await db.exec(`CREATE ROLE authenticated; CREATE ROLE anon; CREATE SCHEMA auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY); INSERT INTO auth.users VALUES ('${student}'),('${admin}'),('${foreign}');
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.actor',true),'')::uuid $$;
CREATE FUNCTION public.has_role(actor uuid, role text) RETURNS boolean LANGUAGE sql AS $$ SELECT actor='${admin}'::uuid AND role='admin' $$;
CREATE TABLE public.intro_lr_attempts(id uuid PRIMARY KEY,user_id uuid,question_id text,correct boolean);
INSERT INTO public.intro_lr_attempts VALUES('${attempt}','${student}','Q1',false),('${later}','${student}','Q1',false);
CREATE TABLE public.bootcamp_kv(user_id uuid,table_name text,record_id text,data jsonb);
INSERT INTO public.bootcamp_kv VALUES('${student}','calibration_attempts','legacy-envelope','{"user_id":"${student}","calibration_module":"M5","calibration_only":true,"item_id":"MC-HS-CAP-1","correct":false}');
CREATE TABLE public.flagged_questions(user_id uuid,qid text); INSERT INTO public.flagged_questions VALUES('${student}','Q1');`);
const before = JSON.stringify((await db.query('SELECT * FROM intro_lr_attempts ORDER BY id')).rows);
const capstoneBefore = JSON.stringify((await db.query('SELECT * FROM bootcamp_kv')).rows);
await db.exec(await readFile(new URL('../../docs/implementation-plans/artifacts/2026-09-30-review-episodes.sql',import.meta.url),'utf8'));
await db.exec('SET ROLE authenticated');
const actor = id => db.query("SELECT set_config('test.actor',$1,false)",[id]);
const open = (sourceId=attempt, reason='missed', selection=null, subject=student, source='intro_lr_attempts') => db.query('SELECT public.open_review_episode_v1($1,$2,$3,$4,$5) AS row',[subject,source,sourceId,reason,selection]);
const append = (episode,id,kind,payload) => db.query('SELECT public.append_review_event_v1($1,$2,$3,$4::jsonb) AS row',[episode,id,kind,JSON.stringify(payload)]);
const rejects = async task => { await assert.rejects(task); checks++; };
await actor(student);
const episode = (await open()).rows[0].row.id;
assert.equal((await open()).rows[0].row.id,episode); checks++;
await rejects(() => open(attempt,'teacher_selected','reason'));
await actor(foreign); await rejects(() => open()); await rejects(() => db.query('SELECT public.read_review_episodes_v1($1)',[student]));
await actor(admin); await rejects(() => open(attempt,'teacher_selected',' '));
const selected = (await open(attempt,'teacher_selected','Compare both conclusions')).rows[0].row;
assert.equal(selected.selection_reason,'Compare both conclusions'); checks++;
await rejects(() => open(attempt,'teacher_selected','different reason'));
await rejects(() => append(selected.id,'66666666-6666-4666-8666-666666666666','complete',{}));
await actor(student);
await rejects(() => append(episode,'66666666-6666-4666-8666-666666666666','complete',{}));
await append(selected.id,'66666666-6666-4666-8666-666666666666','complete',{}); checks++;
const blind='77777777-7777-4777-8777-777777777777', reveal='88888888-8888-4888-8888-888888888888', complete='99999999-9999-4999-8999-999999999999';
await append(episode,blind,'blind_answer',{answer:'B'});
assert.equal((await append(episode,blind,'blind_answer',{answer:'B'})).rows[0].row.id,blind); checks++;
await rejects(() => append(episode,blind,'blind_answer',{answer:'C'}));
await append(episode,reveal,'reveal',{});
await rejects(() => append(episode,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa','blind_answer',{answer:'C'}));
await append(episode,complete,'complete',{error_diagnosis:'scope',right_answer_diagnosis:'matches conclusion'});
assert.equal((await append(episode,complete,'complete',{error_diagnosis:'scope',right_answer_diagnosis:'matches conclusion'})).rows[0].row.id,complete); checks++;
await rejects(() => append(episode,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa','reflection',{text:'late'}));
assert.notEqual((await open(later)).rows[0].row.id,episode); checks++;
assert.equal((await open('legacy-envelope','missed',null,student,'hs_capstone')).rows[0].row.source_id,'legacy-envelope'); checks++;
await rejects(() => db.query('UPDATE public.review_episodes_v1 SET selection_reason=$1 WHERE id=$2',['erase',episode]));
await rejects(() => db.query('DELETE FROM public.review_episode_events_v1 WHERE episode_id=$1',[episode]));
await db.exec('RESET ROLE');
assert.equal(JSON.stringify((await db.query('SELECT * FROM intro_lr_attempts ORDER BY id')).rows),before); checks++;
assert.equal(JSON.stringify((await db.query('SELECT * FROM bootcamp_kv')).rows),capstoneBefore); checks++;
assert.equal((await db.query('SELECT count(*)::int AS count FROM flagged_questions')).rows[0].count,1); checks++;
await db.close();
console.log(JSON.stringify({status:'passed',checks,deployed:false,engine:'isolated PGlite'}));
