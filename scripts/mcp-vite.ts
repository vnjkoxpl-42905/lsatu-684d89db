import { readFile, writeFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { loadEnv, normalizePath, type Plugin, type ResolvedConfig } from "vite";

const require = createRequire(import.meta.url);
const sdkEntry = require.resolve("@lovable.dev/mcp-js");
const sdkRequire = createRequire(sdkEntry);
const { build } = sdkRequire("esbuild") as typeof import("esbuild");
const { version: sdkVersion } = JSON.parse(readFileSync(path.resolve(sdkEntry, "../../package.json"), "utf8")) as { version: string };
const entry = "src/lib/mcp/index.ts";
const output = "supabase/functions/mcp/index.ts";
const banner = "// AUTO-GENERATED by @lovable.dev/mcp-js";

// SDK 0.20 treats Windows drive paths and Vite source aliases as bare npm
// imports. Use its Edge wrapper with a relative entry and resolve @/ locally.
export function supabaseMcpPlugin(): Plugin {
  let config: ResolvedConfig;
  let inputs = new Set<string>();
  let pending = Promise.resolve();

  async function emit() {
    const root = config.root;
    const packageJson = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
    const ranges: Record<string, string> = { ...packageJson.devDependencies, ...packageJson.dependencies };
    const env = loadEnv("production", config.envDir);
    const projectRef = env.VITE_SUPABASE_PROJECT_ID;
    if (!projectRef) throw new Error("MCP generation requires VITE_SUPABASE_PROJECT_ID");
    const bundled = await build({
      stdin: {
        contents: `import mcp from "./${entry}";
import { createSupabaseHandler } from "@lovable.dev/mcp-js/stacks/supabase";
Deno.serve(createSupabaseHandler(mcp, { functionName: "mcp" }));`,
        resolveDir: root,
        sourcefile: "lovable-mcp-supabase-entry.ts",
        loader: "ts",
      },
      absWorkingDir: root,
      define: {
        "import.meta.env.VITE_SUPABASE_PROJECT_ID": JSON.stringify(projectRef),
        "import.meta.env.VITE_CONDITIONAL_FULL_COURSE_ASSIGNMENTS_RELEASED":
          JSON.stringify(env.VITE_CONDITIONAL_FULL_COURSE_ASSIGNMENTS_RELEASED ?? "false"),
      },
      bundle: true,
      write: false,
      metafile: true,
      format: "esm",
      platform: "neutral",
      target: "esnext",
      plugins: [{
        name: "externalize-mcp-npm-imports",
        setup(builder) {
          builder.onResolve({ filter: /^@\// }, ({ path: specifier, kind }) =>
            builder.resolve("./src/" + specifier.slice(2), { resolveDir: root, kind }),
          );
          builder.onResolve({ filter: /^[^./]/ }, ({ path: specifier }) => {
            if (/^(npm|node|jsr|https?|data):/.test(specifier)) return { path: specifier, external: true };
            const packageName = specifier.split("/").slice(0, specifier.startsWith("@") ? 2 : 1).join("/");
            const version = packageName === "@lovable.dev/mcp-js" ? sdkVersion : ranges[packageName];
            const subpath = specifier.slice(packageName.length);
            return { path: `npm:${packageName}${version ? "@" + version : ""}${subpath}`, external: true };
          });
        },
      }],
    });
    inputs = new Set(Object.keys(bundled.metafile.inputs).map((file) => normalizePath(path.resolve(root, file))));
    const filename = path.join(root, output);
    const existing = await readFile(filename, "utf8");
    if (!existing.startsWith(banner)) throw new Error("MCP generator owns only the generated Edge entry");
    const generated = `${banner} \u2014 do not edit. Regenerated by the Vite plugin.
// To take ownership, delete this banner line; the plugin then leaves the file alone.
// supabase function: mcp
// Bundled from ${entry} by @lovable.dev/mcp-js.
// @ts-nocheck: esbuild emits JavaScript. Typecheck the source registry and tools.
${bundled.outputFiles[0].text}`;
    if (existing.replaceAll("\r\n", "\n") !== generated) await writeFile(filename, generated);
  }

  function regenerate() {
    const next = pending.catch(() => {}).then(emit);
    pending = next;
    return next;
  }

  return {
    // The Lovable manifest CLI reads the entry and URL from this plugin API.
    name: "@lovable.dev/mcp-js/supabase",
    api: { get mcpEntry() { return path.resolve(config.root, entry); }, urlPath: "/functions/v1/mcp" },
    configResolved(resolved) {
      config = resolved;
      return regenerate();
    },
    buildStart: regenerate,
    configureServer(server) {
      const changed = (file: string) => {
        if (inputs.has(normalizePath(file))) void regenerate().catch((error: Error) => server.config.logger.error(error.message));
      };
      server.watcher.on("change", changed);
      server.watcher.once("close", () => server.watcher.off("change", changed));
    },
  };
}
