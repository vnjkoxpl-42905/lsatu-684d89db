import { describe, expect, it } from "vitest";
import { SEED_ACTIVITIES } from "./index";

/**
 * The Activities whose items are authored prose, parsed out of the markdown
 * banks. Everything below is about the risk that parsing carries.
 *
 * The captured sections are excluded here and asserted in
 * `read-recall-colour-sections.test.ts` instead. They are not authored, they
 * are lifted verbatim from real LR sections, so half of these invariants would
 * fail on them for the right reason: a section has no reference retelling, its
 * rules are the shared ones the door hands it rather than its own row, and its
 * prompts are somebody else's punctuation, which we may not edit.
 */
const AUTHORED = SEED_ACTIVITIES.filter((a) => a.mode !== "section");

// These Activities are generated by parsing markdown item banks, so the risk is
// silent malformation: a truncated prompt, a dropped credited answer, a gap in
// the ordering. Every item reaches a student, so the shape is asserted here
// rather than trusted.

describe("seed Activities", () => {
  it("ships the seven authored Activities, plus the captured sections, with unique slugs", () => {
    expect(AUTHORED).toHaveLength(7);
    // Uniqueness spans everything seeded: slug is the conflict target the seed
    // migration upserts on, so a collision would silently overwrite a row.
    const slugs = SEED_ACTIVITIES.map((a) => a.slug);
    expect(new Set(slugs).size).toBe(slugs.length);
  });

  it.each(AUTHORED.map((a) => [a.slug, a] as const))(
    "%s is well formed",
    (_slug, activity) => {
      expect(activity.title.trim()).not.toBe("");
      expect(activity.subtitle.trim()).not.toBe("");
      // Every authored Activity is typed. Conditional Rephrase is the one
      // closed-form drill: students work on paper and record one of five
      // diagrams, so classifying it as free text would wrongly imply AI
      // grading. The other authored Activities still accept prose.
      expect(activity.item_format).toBe(activity.slug === "conditional-rephrase" ? "mcq" : "free-text");
      expect(activity.items.length).toBeGreaterThan(0);
    },
  );

  it.each(AUTHORED.map((a) => [a.slug, a] as const))(
    "%s carries a Coach brief so it is not judged by the negation rubric",
    (_slug, activity) => {
      const coach = activity.instructions.coach;
      expect(coach).toBeDefined();
      expect(coach!.drill.trim()).not.toBe("");
      expect(coach!.rubric.length).toBeGreaterThanOrEqual(3);
      expect(coach!.partial_rule).toMatch(/partial/i);
    },
  );

  it.each(AUTHORED.map((a) => [a.slug, a] as const))(
    "%s items are densely ordered from 1 with no empty fields",
    (_slug, activity) => {
      const orders = activity.items.map((i) => i.order);
      expect(orders).toEqual(activity.items.map((_, n) => n + 1));

      for (const item of activity.items) {
        expect(item.prompt.trim().length, `item ${item.order} prompt`).toBeGreaterThan(20);
        expect(item.credited_answers.length, `item ${item.order} answers`).toBeGreaterThan(0);
        for (const answer of item.credited_answers) {
          expect(answer.trim().length, `item ${item.order} answer`).toBeGreaterThan(0);
        }
        expect(item.explanation.trim().length, `item ${item.order} explanation`).toBeGreaterThan(0);
        expect(item.category?.trim().length, `item ${item.order} category`).toBeGreaterThan(0);
        // Emphasis marks are authored on purpose (Spot the Callback marks its
        // callback phrase, Vocab Rehab its target word) and the panel renders
        // them. What must never happen is an unbalanced marker, which is what a
        // bad parse produces and what would surface as a stray asterisk.
        const strong = item.prompt.match(/\*\*/g)?.length ?? 0;
        expect(strong % 2, `item ${item.order} unbalanced **`).toBe(0);
        const all = item.prompt.match(/\*/g)?.length ?? 0;
        expect(all % 2, `item ${item.order} unbalanced *`).toBe(0);
      }
    },
  );

  it.each(AUTHORED.map((a) => [a.slug, a] as const))(
    "%s student-facing copy carries no em-dashes",
    (_slug, activity) => {
      const studentFacing = [
        activity.title,
        activity.subtitle,
        activity.instructions.tagline ?? "",
        activity.instructions.task ?? "",
        ...(activity.instructions.rules ?? []),
        ...activity.items.map((i) => i.prompt),
        ...activity.items.flatMap((i) => i.credited_answers),
      ];
      for (const text of studentFacing) {
        expect(text, `"${text.slice(0, 60)}"`).not.toContain("—");
      }
    },
  );
});
