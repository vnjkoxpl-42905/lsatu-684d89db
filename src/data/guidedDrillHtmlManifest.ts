function normalizeLookup(value: string | null | undefined): string {
  return (value ?? '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

export function findGuidedDrillHtmlBySlug(slug: string | null | undefined) {
  const normalizedSlug = normalizeLookup(slug);
  return guidedDrillHtmlManifest.find((entry) => entry.slug === normalizedSlug) ?? null;
}

export function findGuidedDrillHtmlByDrill(drill: { slug?: string | null; title?: string | null; source_file?: string | null } | null | undefined) {
  if (!drill) return null;
  const sourceFile = drill.source_file?.split(/[\\/]/).pop();
  if (sourceFile) {
    const sourceMatch = guidedDrillHtmlManifest.find((entry) => entry.sourceFile === sourceFile);
    if (sourceMatch) return sourceMatch;
  }
  return findGuidedDrillHtmlBySlug(drill.slug) ?? findGuidedDrillHtmlBySlug(drill.title);
}
