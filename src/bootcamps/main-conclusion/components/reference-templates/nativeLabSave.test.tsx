import { act, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const { saveNativeLabSubmission } = vi.hoisted(() => ({ saveNativeLabSubmission: vi.fn() }));
vi.mock('@/bootcamps/main-conclusion/lib/nativeLabAttempt', () => ({ saveNativeLabSubmission }));
import { RebuttalVsFirstReplicaTemplate } from './RebuttalVsFirstReplicaTemplate';
import { CANONICAL_REBUTTAL_VS_FIRST_STAGE_SETS } from '@/bootcamps/main-conclusion/data/reference-drills/canonicalStructureQuestions';
import { ORDERED_CANONICAL_MAIN_CONCLUSION_QUESTIONS } from '@/bootcamps/main-conclusion/data/reference-drills/canonicalStructureQuestions';
import { MainConclusionReplicaTemplate } from './MainConclusionReplicaTemplate';
beforeEach(() => saveNativeLabSubmission.mockReset().mockResolvedValue(undefined));
afterEach(() => vi.useRealTimers());
it('keeps selected response, withholds feedback and completion on failure, retries same response UUID', async () => {
  saveNativeLabSubmission.mockRejectedValueOnce(new Error('offline'));
  const complete = vi.fn().mockResolvedValue(undefined);
  const stage = { ...CANONICAL_REBUTTAL_VS_FIRST_STAGE_SETS[0], questions: CANONICAL_REBUTTAL_VS_FIRST_STAGE_SETS[0].questions.slice(0, 1) };
  render(<RebuttalVsFirstReplicaTemplate title="Lab" stages={[stage]} saveNativeAnswers nativeUserId="student" onComplete={complete} />);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'First-sentence conclusion' })); });
  expect(screen.getByRole('alert')).toHaveTextContent('not been confirmed');
  expect(screen.queryByRole('button', { name: 'Finish Lab' })).not.toBeInTheDocument();
  expect(complete).not.toHaveBeenCalled();
  const response = saveNativeLabSubmission.mock.calls[0][0];
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Try saving again' })); });
  expect(saveNativeLabSubmission.mock.calls[1][0]).toEqual(response);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Finish Lab' })); });
  expect(complete).toHaveBeenCalledTimes(1); expect(screen.getByText('Lab completion saved.')).toBeInTheDocument();
});
it('retains saved answer and retries rejected completion without inserting another answer', async () => {
  const complete = vi.fn().mockRejectedValueOnce(new Error('offline')).mockResolvedValue(undefined);
  const stage = { ...CANONICAL_REBUTTAL_VS_FIRST_STAGE_SETS[0], questions: CANONICAL_REBUTTAL_VS_FIRST_STAGE_SETS[0].questions.slice(0, 1) };
  render(<RebuttalVsFirstReplicaTemplate title="Lab" stages={[stage]} saveNativeAnswers nativeUserId="student" onComplete={complete} />);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'First-sentence conclusion' })); });
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Finish Lab' })); });
  expect(screen.getByRole('alert')).toHaveTextContent('Completion could not be saved');
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Finish Lab' })); });
  expect(saveNativeLabSubmission).toHaveBeenCalledTimes(1); expect(complete).toHaveBeenCalledTimes(2);
});
it('holds Main Conclusion feedback and advancement until its selected answer is acknowledged', async () => {
  vi.useFakeTimers(); saveNativeLabSubmission.mockRejectedValueOnce(new Error('offline'));
  const question = ORDERED_CANONICAL_MAIN_CONCLUSION_QUESTIONS[0]; const complete = vi.fn().mockResolvedValue(undefined);
  const view = render(<MainConclusionReplicaTemplate title="Main Conclusion" questions={[question]} saveNativeAnswers nativeUserId="student" onComplete={complete} />);
  fireEvent.click(view.container.querySelectorAll('[aria-pressed]')[question.correctMainConclusionIndex]);
  act(() => { vi.advanceTimersByTime(350); });
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'ANALYZE SELECTION' })); });
  expect(screen.getByRole('alert')).toHaveTextContent('not been confirmed');
  expect(screen.queryByRole('button', { name: /NEXT QUESTION/ })).not.toBeInTheDocument();
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Try saving again' })); });
  act(() => { vi.advanceTimersByTime(1000); });
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: /NEXT QUESTION/ })); });
  expect(complete).toHaveBeenCalledTimes(1);
  expect(saveNativeLabSubmission.mock.calls[0][0]).toEqual(saveNativeLabSubmission.mock.calls[1][0]);
});
